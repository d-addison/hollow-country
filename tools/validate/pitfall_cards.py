"""Generate docs/pitfalls/*.md, the pitfall cards workers and briefs point at.

Standard library only. The cards are derived, never hand-edited:
  * every HC-E / HC-L / HC-O / HC-S / HC-P rule message in enforce_lint.RULES and enforce_perf.RULES,
  * every comment under mods/**/*.c that cites a build ("build NNN") or an issue ("#NNN") and says what
    failed natively (crash, compile error, engine behaviour),
  * the compile pitfalls of 2026-11-22 that the lint does not catch yet.
Each rule and each comment lands in exactly one of four cards: enforce-pitfalls, persistence, dep-bridge,
perf-tick. Output carries no line numbers or dates, so unrelated edits do not churn it.

Usage: python3 -B -m tools.validate.pitfall_cards [--check] [--root DIR] [--out DIR]
  default       write the cards (replace docs/pitfalls/*.md)
  --check       read-only; fail when a card differs from fresh generation (used by regenerate_all)
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = Path('docs/pitfalls')
MARKER = '<!-- Generated by tools.validate.pitfall_cards; do not edit by hand. Regenerate with that tool. -->'
EXCERPT_LIMIT = 360

CARDS = ('enforce-pitfalls', 'persistence', 'dep-bridge', 'perf-tick')

TITLES = {
    'enforce-pitfalls': 'Enforce Script pitfalls',
    'persistence': 'Persistence pitfalls',
    'dep-bridge': 'Dependency bridge pitfalls',
    'perf-tick': 'Tick and performance pitfalls',
}

INTRO = {
    'enforce-pitfalls': (
        'Read before editing any `mods/**/*.c`. The native compiler is stricter than the lint, so every rule below '
        'was paid for by a failed native compile or a crash. Function scope is flat (one declaration per name per '
        'function, none in sibling blocks), there are no ternaries, owned arrays and maps are `ref`, and a fresh '
        'result is held in a local before it is passed on.'),
    'persistence': (
        'Read before touching stored data: stores, journals, saves, JSON loaders and migrations. The friend server '
        'can never be wiped, so every stored-format change needs a migration that runs at start, every on-disk '
        'state must load or self-repair (never refuse forever), no receipt is lost and no loot is duplicated. '
        'Saves go through HCSaveScheduler and the staged writer, one native file operation per step.'),
    'dep-bridge': (
        'Read before calling Expansion AI, COT or CF. Dependency calls go only through the HC bridge classes, '
        'which validate invariants and refuse with a reason code (lint HC-E022 and HC-E027). A raw `eAIGroup` '
        'handle is not auto-nulled when the group is freed: hold it through `HCXAIGroupHold` or store a group id '
        'and resolve it before every use.'),
    'perf-tick': (
        'Read before writing tick, OnUpdate or save-step code. Work is bounded per tick: use HCWorkBudget, '
        'HCSaveScheduler, HCModuleReadiness and HCPerfConfig, register every work slot, never scan a whole '
        'collection or print per item on a tick path, and keep file I/O inside the staged writer.'),
}

# Rules that belong to a card other than the default (HC-P* -> perf-tick, everything else -> enforce-pitfalls).
RULE_CARD = {
    'HC-E010': 'persistence', 'HC-E016': 'persistence', 'HC-E017': 'persistence', 'HC-S005': 'persistence',
    'HC-P003': 'persistence', 'HC-P008': 'persistence', 'HC-P009': 'persistence',
    'HC-E022': 'dep-bridge', 'HC-E027': 'dep-bridge',
}

# 2026-11-22 native compile failures the lint does not catch yet.
COMPILE_PITFALLS = (
    ('Enforce keyword as an identifier',
     'A variable, member or parameter named `owned`, `out`, `inout`, `local`, `auto`, `ref`, `autoptr`, '
     '`proto`, `native`, `volatile`, `notnull`, `private`, `protected`, `static`, `const`, `typename`, '
     '`thread` or `event` fails the native compile ("Expected name"). Rename it.'),
    ('Method named `Wait`',
     'A method named `Wait` clashes with the engine. Name it for what it waits on.'),
    ('Bitwise operator in a float expression',
     '`&`, `|`, `^`, `<<` and `>>` inside a float expression fail the native compile. Keep bitwise work in '
     'int-only statements and convert afterwards.'),
    ('Reading a field the class no longer has',
     'Removing or renaming a field leaves readers in other files compiling only until the native pass. '
     'Search every file of the modded-class chain for the old name before reporting done.'),
    ('Modded override with a different signature',
     'A modded override must match the native signature exactly (name, parameter types, return type). Open the '
     'installed native script and copy the declaration.'),
)

_COMMENT_LINE = re.compile(r'^\s*//+\s?(.*)$')
_TRAILING = re.compile(r'^(?P<code>[^/"\']*(?:"[^"]*"[^/"\']*)*\S)\s+//+\s?(?P<text>.*)$')
_CITATION = re.compile(r'\bbuild\s+\d+|\[build \d+\]|#\d+', re.I)
_BUILD = re.compile(r'\bbuild\s+\d+|\[build \d+\]', re.I)
_FAILURE = re.compile(
    r'crash|access violation|native compile|compile error|\bVME\b|dangling|\bfreed\b|released (?:mid|at once|early)|'
    r'too complex|unknown type|syntax error|wrong parameter|incompatible parameter|not managed|'
    r'logged thousands|\bstall(?:ed)?\b|\bhitch', re.I)
_DEP = re.compile(r'expansion|\beAI\w*|\bCOT\b|\bCF\b|bridge', re.I)
_PERSIST = re.compile(r'\b(?:save[ds]?|saving|persist\w*|migrat\w*|torn|journal|filehandle|jsonfileloader|profile|store[ds]?)\b', re.I)
_PERF = re.compile(r'\b(?:tick\w*|budget\w*|onupdate|frame|perf\w*|per-tick|stall\w*|hitch\w*|bounded)\b', re.I)


def rule_tables():
    from tools.validate import enforce_lint, enforce_perf
    rules = dict(enforce_lint.RULES)
    rules.update(enforce_perf.RULES)
    return rules


def rule_card(rule_id):
    if rule_id in RULE_CARD:
        return RULE_CARD[rule_id]
    return 'perf-tick' if rule_id.startswith('HC-P') else 'enforce-pitfalls'


def comment_card(path, text):
    if 'HollowCountryExpansionAI' in path or _DEP.search(text):
        return 'dep-bridge'
    if _PERSIST.search(text):
        return 'persistence'
    if _PERF.search(text):
        return 'perf-tick'
    return 'enforce-pitfalls'


def excerpt(text):
    text = re.sub(r'\s+', ' ', text).strip()
    if len(text) > EXCERPT_LIMIT:
        text = text[:EXCERPT_LIMIT].rsplit(' ', 1)[0] + ' ...'
    return text


def qualifies(window):
    if _BUILD.search(window):
        return True
    return bool(_CITATION.search(window)) and bool(_FAILURE.search(window))


def file_comments(text):
    """Yield each comment block (consecutive full-line comments) and each trailing comment as a list of lines."""
    block = []
    for line in text.splitlines():
        match = _COMMENT_LINE.match(line)
        if match:
            block.append(match.group(1).strip())
            continue
        if block:
            yield block
            block = []
        trailing = _TRAILING.match(line)
        if trailing:
            yield [trailing.group('text').strip()]
    if block:
        yield block


def cited_excerpts(block):
    """The runs of lines in a comment block where a citation and its native failure sit within one line of each other."""
    marked = set()
    for index in range(len(block)):
        window = range(max(0, index - 1), min(len(block), index + 2))
        if qualifies(' '.join(block[i] for i in window)):
            marked.update(window)
    runs, current = [], []
    for index in sorted(marked):
        if current and index != current[-1] + 1:
            runs.append(current)
            current = []
        current.append(index)
    if current:
        runs.append(current)
    return [excerpt(' '.join(block[i] for i in run)) for run in runs]


def native_failure_comments(root):
    """Sorted (relative path, excerpt) pairs for every comment that cites a build or issue and a native failure."""
    found = set()
    base = Path(root) / 'mods'
    for path in sorted(base.rglob('*.c')) if base.is_dir() else []:
        try:
            text = path.read_text(encoding='utf-8', errors='replace')
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        for block in file_comments(text):
            for text_run in cited_excerpts(block):
                found.add((relative, text_run))
    return sorted(found)


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def render_card(name, rules, comments):
    lines = [MARKER, '', '# ' + TITLES[name], '', INTRO[name], '',
             f'Skill: `hc-{name}`. Rule ids come from `tools/validate/enforce_lint.py` and '
             '`tools/validate/enforce_perf.py`; each rule or cited comment appears on exactly one card.', '']
    mine = sorted((rule_id, message) for rule_id, message in rules.items() if rule_card(rule_id) == name)
    if mine:
        lines += ['## Lint and perf rules', '', '| Rule | What it rejects |', '|---|---|']
        lines += [f'| {rule_id} | {cell(message)} |' for rule_id, message in mine]
        lines.append('')
    if name == 'enforce-pitfalls':
        lines += ['## Native compile pitfalls the lint does not catch yet', '']
        lines += [f'- **{title}.** {body}' for title, body in COMPILE_PITFALLS]
        lines.append('')
    cited = [(path, text) for path, text in comments if comment_card(path, text) == name]
    if cited:
        lines += ['## Native failures cited in the code', '',
                  'Comments under `mods/` that cite a build or issue and say what failed. '
                  'Open the file before changing the code they describe.', '']
        current = None
        for path, text in cited:
            if path != current:
                lines += ['', f'### `{path}`', '']
                current = path
            lines.append('- ' + text)
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'


def build_cards(root=ROOT):
    rules = rule_tables()
    comments = native_failure_comments(root)
    return {name: render_card(name, rules, comments) for name in CARDS}


def check_cards(root, out):
    """Return the problems between the cards on disk and fresh generation."""
    problems = []
    fresh = build_cards(root)
    folder = Path(root) / out
    for name, content in fresh.items():
        path = folder / (name + '.md')
        if not path.is_file():
            problems.append(f'{name}.md missing')
        elif path.read_text(encoding='utf-8') != content:
            problems.append(f'{name}.md differs from fresh generation')
    if folder.is_dir():
        for path in sorted(folder.glob('*.md')):
            if path.stem not in fresh:
                problems.append(f'{path.name} is not a generated card')
    return problems


def write_cards(root, out):
    folder = Path(root) / out
    folder.mkdir(parents=True, exist_ok=True)
    fresh = build_cards(root)
    for path in folder.glob('*.md'):
        if path.stem not in fresh:
            path.unlink()
    for name, content in fresh.items():
        (folder / (name + '.md')).write_text(content, encoding='utf-8', newline='\n')
    return fresh


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='read-only comparison with fresh generation')
    parser.add_argument('--root', type=Path, default=ROOT, help='repository root to scan and write under')
    parser.add_argument('--out', type=Path, default=OUT, help='card folder relative to the root')
    args = parser.parse_args(argv)
    if args.check:
        problems = check_cards(args.root, args.out)
        for problem in problems:
            print('pitfall_cards: ' + problem)
        print(f'pitfall_cards: {"fail" if problems else "pass"} cards={len(CARDS)} problems={len(problems)}')
        return 1 if problems else 0
    fresh = write_cards(args.root, args.out)
    print(f'pitfall_cards: wrote cards={len(fresh)} rules={len(rule_tables())}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
