"""Generate vanilla-derived inventory overrides (stdlib; runtime acceptance pending).

python3 -m tools.package.inventory_sizes --addons /path/to/vanilla/addons --write
python3 -m tools.package.inventory_sizes --addons /path/to/vanilla/addons --check

Normal modes reread installed configs and compare the bounded reviewed manifest.
After changing rules/build, --refresh-review deliberately refreshes that manifest
before writing. --review-only --check is an offline source-consistency check;
it does not verify vanilla or authorize a write. No extracted config is saved.
"""
import argparse
from collections import Counter
import json
import math
from pathlib import Path
import re
import sys

if __package__ in (None, ''):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.audit import pbo_config

ROOT = Path(__file__).resolve().parents[2]
BEGIN = '// BEGIN HC inventory sizes (generated by tools/package/inventory_sizes.py)'
END = '// END HC inventory sizes'
# overlay_remove.py leaves this marker (never BEGIN) after dropping the generated block, so a later
# --write refuses rather than regenerating a duplicate authored class.
REMOVED = '// HC inventory sizes removed by tools/package/overlay_remove.py'
# Authored native-slot extensions carried inside the generated rows (class -> extra fields).
AUTHORED_SLOT_ROWS = {
    'TortillaBag': ' attachments[] = {"Chemlight", "WalkieTalkie", "Backpack_1", "NBCBag", "helmetFlashlight"};',
}
IDENTIFIER = re.compile(r'[A-Za-z_][A-Za-z0-9_]*\Z')
FIELDS = {'scope', 'itemSize', 'itemsCargoSize', 'inventorySlot', 'weight'}


def _config_rows(data):
    """Use the existing bounded read-only reader, retaining numeric size arrays.

    Its public parse_rap intentionally filters arrays to strings for the firearm
    audit. _Rap.entries is the same decoder, with its existing size/count bounds;
    no reader globals or implementation are changed here.
    """
    if len(data) > pbo_config.MAX_CONFIG_BYTES or data[:4] != b'\0raP':
        raise ValueError('expected bounded vanilla rapified config.bin')
    rap = pbo_config._Rap(data)
    _, roots = rap.entries(16)
    patches, rows = {}, {}
    for kind, root, offset in roots:
        if kind != 'class' or root.lower() not in {'cfgpatches', 'cfgvehicles'}:
            continue
        _, children = rap.entries(offset)
        for ckind, name, body in children:
            if ckind != 'class':
                continue
            parent, entries = rap.entries(body)
            fields = {}
            for fkind, field, value in entries:
                if fkind in {'value', 'array'}:
                    fields[field] = value
                elif fkind == 'array+' and field in FIELDS | {'requiredAddons', 'units'}:
                    raise ValueError('unsupported inherited array append: ' + name + '.' + field)
            if root.lower() == 'cfgpatches':
                patches[name] = fields
            else:
                rows[name] = {'parent': parent, 'fields': {k: v for k, v in fields.items() if k in FIELDS}}
    return patches, rows


def load_vanilla(addons):
    """Read only vanilla source families from the explicitly supplied addons directory.

    Sort config members by their verified CfgPatches dependencies before merging
    reopenings. The sole patch (or unique units[] owner) binds each definition.
    """
    addons = Path(addons)
    if not addons.is_dir():
        raise ValueError('vanilla addons directory missing')
    documents, all_patches = [], set()
    families = ('characters_', 'gear_', 'weapon_', 'weapons_', 'vehicles_')
    for path in sorted(addons.glob('*.pbo')):
        if not (path.name.startswith(families) or path.name in {'dz.pbo', 'plants.pbo'}):
            continue
        index = pbo_config.read_pbo_index(path)
        for entry in sorted(index['entries'], key=lambda e: e['name'].lower()):
            if not entry['name'].lower().endswith('config.bin'):
                continue
            data = pbo_config.read_member(path, index, entry['name'])
            patches, rows = _config_rows(data)
            all_patches.update(patches)
            documents.append({'pbo': path.name, 'member': entry['name'], 'patches': patches,
                              'rows': rows})
    if not documents:
        raise ValueError('no vanilla config.bin members found')
    definitions, loaded, pending = {}, set(), documents[:]
    while pending:
        progressed = False
        for doc in pending[:]:
            dependencies = {dep.lower() for p in doc['patches'].values()
                            for dep in p.get('requiredAddons', [])}
            local = {p.lower() for p in doc['patches']}
            known = {p.lower() for p in all_patches}
            if not ((dependencies & known) - local) <= loaded:
                continue
            for name, row in doc['rows'].items():
                if not IDENTIFIER.fullmatch(name) or (row['parent'] and not IDENTIFIER.fullmatch(row['parent'])):
                    raise ValueError('invalid vanilla class/parent name')
                owners = [p for p, fields in doc['patches'].items()
                          if name.lower() in {u.lower() for u in fields.get('units', [])}]
                owner = owners[0] if len(owners) == 1 else (
                    next(iter(doc['patches'])) if len(doc['patches']) == 1 else None)
                key = name.lower()
                previous = definitions.get(key)
                # Empty class reopenings (e.g. Clothing in gear_medical) are
                # references, not a new defining addon for the inherited class.
                if previous and not row['fields']:
                    if row['parent'] and previous['parent'].lower() != row['parent'].lower():
                        raise ValueError('conflicting vanilla parent: ' + name)
                    continue
                fields = {**(previous['fields'] if previous else {}), **row['fields']}
                definitions[key] = {'name': name, 'parent': row['parent'] or (
                    previous['parent'] if previous else ''), 'addon': owner,
                    'pbo': doc['pbo'], 'member': doc['member'], 'fields': fields}
            loaded.update(local)
            pending.remove(doc)
            progressed = True
        if not progressed:
            raise ValueError('cyclic vanilla addon dependencies: ' + ', '.join(d['member'] for d in pending))
    return {r['name']: r for r in definitions.values()}, all_patches


def _resolved(definitions):
    lookup = {n.lower(): row for n, row in definitions.items()}
    result, visiting = {}, set()

    def resolve(name):
        key = name.lower()
        if key in result:
            return result[key]
        if key in visiting:
            raise ValueError('cyclic vanilla class ancestry: ' + name)
        row = lookup[key]
        visiting.add(key)
        parent = row['parent'] or ''
        base = resolve(parent) if parent.lower() in lookup else {'fields': {}, 'ancestors': []}
        value = {**row, 'fields': {**base['fields'], **row['fields']},
                 'ancestors': ([parent] + base['ancestors']) if parent else []}
        visiting.remove(key)
        result[key] = value
        return value

    for name in sorted(definitions):
        resolve(name)
    return result


def _size(value):
    if value is None or value == []:
        return None
    if not isinstance(value, list) or len(value) != 2 or any(
            type(v) not in (int, float) or not math.isfinite(v) or v < 0 or int(v) != v for v in value):
        raise ValueError('unsupported numeric inventory dimensions: ' + repr(value))
    return [int(v) for v in value] if all(v > 0 for v in value) else None


def _weight(value):
    # Vanilla includes string literals such as "200g". Unknown units stay unknown.
    if isinstance(value, str):
        match = re.fullmatch(r'([0-9]+(?:\.[0-9]+)?)\s*(g|kg)', value.strip(), re.I)
        if not match:
            return None
        return float(match[1]) * (1000 if match[2].lower() == 'kg' else 1)
    return value if type(value) in (int, float) and math.isfinite(value) and value >= 0 else None


def select_changes(definitions, rules):
    """Return sorted bounded overrides and exclusion counts from explicit class data."""
    resolved = _resolved(definitions)
    changes, excluded = {}, Counter()
    blocked = {n.lower() for n in rules['exclude_ancestor_names']}
    multiplier = rules['backpack_row_multiplier']
    if not isinstance(multiplier, (int, float)) or not math.isfinite(multiplier) or not 1 <= multiplier <= 3:
        raise ValueError('backpack multiplier must be between 1 and 3')
    if rules['square_tie'] != 'shrink_width':
        raise ValueError('unsupported square tie policy')
    for key, row in sorted(resolved.items()):
        name, fields, addon = row['name'], row['fields'], row['addon']
        size, cargo = _size(fields.get('itemSize')), _size(fields.get('itemsCargoSize'))
        ancestors = {n.lower() for n in [name, *row['ancestors']]}
        slots = {s.lower() for s in fields.get('inventorySlot', [])}
        prop, category, old, new = 'itemSize', 'general', size, None
        if name in rules['exclude']:
            excluded['explicit-exclude'] += 1
            continue
        if cargo and 'back' in slots:
            prop, category, old = 'itemsCargoSize', 'backpacks', cargo
            new = [cargo[0], math.ceil(cargo[1] * multiplier)]
        elif cargo:
            excluded['cargo-holder'] += 1
            continue
        elif fields.get('scope') != 2 or size is None:
            excluded['not-public-inventory'] += 1
            continue
        elif (blocked & ancestors or (addon or '').startswith(tuple(rules['exclude_addon_prefixes'])) or
              any(s.startswith(tuple(rules['exclude_inventory_slot_prefixes'])) for s in slots)):
            excluded['firearm-or-weapon-attachment'] += 1
            continue
        elif not row['parent']:
            raise ValueError('inventory override candidate requires real vanilla parent: ' + name)
        elif not (ancestors & {'inventory_base', 'clothing', 'clothing_base', 'edible_base'}):
            excluded['unresolved-inventory-ancestry'] += 1
            continue
        else:
            area = size[0] * size[1]
            medical = name in rules['medical_include'] or addon in rules['medical_addons']
            if area >= 5:
                excluded['area-outside-rules'] += 1
                continue
            if medical and (area <= rules['medical_max_area'] or name in rules['medical_include']):
                category, new = 'medical', [1, 1]
            elif area in rules['general_areas']:
                new = size[:]
                side = 0 if size[0] >= size[1] else 1
                new[side] -= 1
            elif area == 2:
                weight = _weight(fields.get('weight'))
                if (addon in rules['consumable_addons'] or name in rules['consumable_include'] or
                        (addon in rules['tool_addons'] and weight is not None and
                         weight < rules['small_tool_max_weight_grams_exclusive'])):
                    new = [1, 1]
                else:
                    excluded['two-cell-category-or-weight'] += 1
            else:
                excluded['area-outside-rules'] += 1
        if new is None or new == old:
            continue
        if not row['parent']:
            raise ValueError('override requires real vanilla parent: ' + name)
        if not addon:
            raise ValueError('ambiguous defining CfgPatches addon: ' + name)
        changes[key] = {k: row[k] for k in ('name', 'parent', 'addon', 'pbo', 'member')}
        changes[key].update(property=prop, vanilla=old, new=new, category=category)
    # Do not let excluded descendants inherit a reduced shell or non-backpacks
    # inherit enlarged cargo. Removing a proposal may protect another ancestor.
    while True:
        remove = set()
        for key, change in changes.items():
            prop = change['property']
            for child_key, child in resolved.items():
                if child_key == key or key not in {a.lower() for a in child['ancestors']}:
                    continue
                intervening = []
                for ancestor in [child['name'], *child['ancestors']]:
                    if ancestor.lower() == key:
                        break
                    intervening.append(ancestor.lower())
                if any(prop in definitions[resolved[a]['name']]['fields'] for a in intervening if a in resolved):
                    continue
                if child_key not in changes or changes[child_key]['property'] != prop:
                    remove.add(key)
        if not remove:
            break
        for key in remove:
            del changes[key]
            excluded['protect-excluded-descendant'] += 1
    return sorted(changes.values(), key=lambda r: r['name'].lower()), dict(sorted(excluded.items()))


def verify_review(changes, reviewed):
    if changes != reviewed:
        raise ValueError('vanilla/rules differ from reviewed overrides; inspect then use --refresh-review --write')


def render_block(changes):
    lines = ['    ' + BEGIN, '    // Vanilla-derived playtest values; DayZ runtime acceptance pending.']
    # Overridden parents are defined below (before their children), so only external
    # parents get a forward declaration; a class is never both declared and defined.
    overridden = {r['name'].lower() for r in changes}
    for parent in sorted({r['parent'] for r in changes if r['parent'].lower() not in overridden}, key=str.lower):
        if not IDENTIFIER.fullmatch(parent):
            raise ValueError('invalid parent identifier')
        lines.append(f'    class {parent};')
    # Parent definitions precede descendants when both are overridden.
    pending = {r['name'].lower(): r for r in changes}
    while pending:
        ready = [r for r in pending.values() if r['parent'].lower() not in pending]
        if not ready:
            raise ValueError('cyclic override parents')
        for row in sorted(ready, key=lambda r: r['name'].lower()):
            if not IDENTIFIER.fullmatch(row['name']) or row['property'] not in {'itemSize', 'itemsCargoSize'}:
                raise ValueError('invalid override class/property')
            old, new = row['vanilla'], row['new']
            lines.append(f'    // {row["category"]}; {row["addon"]}; {row["pbo"]}:{row["member"]}; '
                         f'vanilla {row["property"]} {old[0]}x{old[1]} -> {new[0]}x{new[1]}')
            # Preserve HC-52's authored native-slot extension when sizes regenerate.
            # Vanilla evidence: ~/.cache/hollow-country/wine-server-20261116/addons/
            # characters_backpacks.pbo:config.bin; slot-table tests pin preservation.
            extra_fields = AUTHORED_SLOT_ROWS.get(row['name'], '')
            lines.append(f'    class {row["name"]}: {row["parent"]} '
                         f'{{ {row["property"]}[] = {{{new[0]}, {new[1]}}};{extra_fields} }};')
            del pending[row['name'].lower()]
    lines.append('    ' + END)
    return '\n'.join(lines) + '\n'


def update_config(config, changes):
    """Modify only our marked region and the HollowCountry requiredAddons line."""
    block = render_block(changes)
    if REMOVED in config:
        raise ValueError('inventory overrides were removed by overlay_remove; restore config.cpp from '
                         'source control before regenerating')
    if config.count(BEGIN) != config.count(END) or config.count(BEGIN) > 1:
        raise ValueError('stale/malformed inventory markers')
    if BEGIN in config:
        config, count = re.subn(r'(?m)^[ \t]*' + re.escape(BEGIN) + r'.*?^[ \t]*' + re.escape(END) + r'\n?',
                                lambda _: block, config, flags=re.S)
        if count != 1:
            raise ValueError('stale/malformed inventory block')
    else:
        match = re.search(r'\bclass\s+CfgVehicles\s*\{', config)
        if not match or len(re.findall(r'\bclass\s+CfgVehicles\s*\{', config)) != 1:
            raise ValueError('stale: expected one existing CfgVehicles')
        start, depth = match.end(), 1
        # Existing config is authored text; use the reader's comment/string
        # stripping to find the matching brace without parsing nested classes.
        # Map the original braces, ignoring comments and strings.
        tokens = re.finditer(r'"(?:[^"]|"")*"|//[^\n]*|/\*.*?\*/|[{}]', config[start:], re.S)
        for token in tokens:
            if token.group() == '{':
                depth += 1
            elif token.group() == '}':
                depth -= 1
                if depth == 0:
                    at = start + token.start()
                    config = config[:at] + block + config[at:]
                    break
        else:
            raise ValueError('stale: unclosed CfgVehicles')
    pattern = r'(requiredAddons\[\]\s*=\s*\{)([^}]*)(\};)'
    matches = list(re.finditer(pattern, config))
    if len(matches) != 1:
        raise ValueError('stale: expected one requiredAddons line')
    required = matches[0]
    existing = re.findall(r'"([^"\n]+)"', required[2])
    missing = sorted({r['addon'] for r in changes} - set(existing), key=str.lower)
    value = ', '.join(json.dumps(n) for n in [*existing, *missing])
    return config[:required.start(2)] + value + config[required.end(2):]


def check_config(config, changes):
    if update_config(config, changes) != config:
        raise ValueError('stale inventory block or requiredAddons; regenerate with --write')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--addons', type=Path)
    parser.add_argument('--rules', type=Path, default=ROOT / 'config/inventory-sizes.json')
    parser.add_argument('--config', type=Path, default=ROOT / 'mods/HollowCountry/config.cpp')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    parser.add_argument('--refresh-review', action='store_true')
    parser.add_argument('--review-only', action='store_true')
    args = parser.parse_args(argv)
    try:
        rules = json.loads(args.rules.read_text())
        if args.review_only:
            if not args.check or args.refresh_review:
                raise ValueError('--review-only is limited to offline --check')
            changes, exclusions = rules['reviewed_overrides'], {}
        else:
            if args.addons is None:
                raise ValueError('--addons must name the installed vanilla directory')
            definitions, patches = load_vanilla(args.addons)
            changes, exclusions = select_changes(definitions, rules)
            if not {r['addon'] for r in changes} <= patches:
                raise ValueError('override addon not verified in vanilla CfgPatches')
            if args.refresh_review:
                if not args.write:
                    raise ValueError('--refresh-review requires --write')
                rules['reviewed_overrides'] = changes
            else:
                verify_review(changes, rules['reviewed_overrides'])
        config = args.config.read_text()
        updated = update_config(config, changes)
        if args.check:
            check_config(config, changes)
        elif args.write:
            if args.refresh_review:
                args.rules.write_text(json.dumps(rules, indent=2) + '\n')
            args.config.write_text(updated)
        else:
            print(render_block(changes), end='')
        print(json.dumps({'counts': dict(sorted(Counter(r['category'] for r in changes).items())),
                          'excluded': exclusions, 'vanilla_verified': not args.review_only,
                          'runtime_acceptance': 'pending'}), file=sys.stderr)
    except (ValueError, OSError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
