"""Generate ancestry-based inventory overrides from vanilla and the declared stack (stdlib; runtime acceptance pending).

python3 -m tools.package.inventory_sizes --addons /path/to/vanilla/addons --write
python3 -m tools.package.inventory_sizes --addons /path/to/vanilla/addons --check

Normal modes reread installed configs and compare the bounded reviewed manifest.
After changing rules/build, --refresh-review deliberately refreshes that manifest
before writing. --review-only --check is an offline source-consistency check;
it does not verify installed inputs or authorize a write. No extracted config is saved.
"""
