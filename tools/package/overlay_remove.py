"""Coordinate overlay removal from a stopped private mission and its addon.

Loot and vehicle overlays roll back through their install receipts. The
inventory overrides are generated config inside the HC PBO, so they cannot be
undone by a mission rollback. Name the addon (--addon-source DIR, or
--addon-pbo FILE for an installed hollowcountry.pbo) and --pbo-out DIR to
produce a reviewable replacement PBO without the generated block, a receipt and
a config diff. The replacement is unsigned and never overwrites the installed
file: sign it, install it on the server and redistribute it to clients. A
scratch rehearsal and the replacement build precede every live removal. The
operation is resumable, not a transaction across installers; keep the server
stopped and retain recovery data if any live rollback refuses.
"""
import argparse
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile

if __package__ in (None, ''):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.package import economy, loot_boost, travel

OVERLAYS = ('loot', 'inventory', 'vehicles')
INVENTORY_GAP = ('inventory receipt rollback unavailable: inventory_sizes.py generates '
                 'CfgVehicles overrides inside the HC PBO; mission rollback cannot remove it. '
                 'Name --addon-source or --addon-pbo plus --pbo-out to build a reviewable '
                 'replacement addon without that generated block.')
# Mirrors tools/package/inventory_sizes.py (not bundled with the operator helpers); a test pins parity.
INVENTORY_BEGIN = '// BEGIN HC inventory sizes (generated by tools/package/inventory_sizes.py)'
INVENTORY_END = '// END HC inventory sizes'
INVENTORY_REMOVED = '// HC inventory sizes removed by tools/package/overlay_remove.py'
AUTHORED_SLOT_ROWS = {
    'TortillaBag': ' attachments[] = {"Chemlight", "WalkieTalkie", "Backpack_1", "NBCBag", "helmetFlashlight"};',
}
REPLACEMENT = 'hollowcountry.no-inventory.pbo'
RECEIPT = 'hollowcountry.no-inventory.receipt.json'
DIFF = 'config.cpp.diff'
_ID = r'[A-Za-z_][A-Za-z0-9_]*'
_FORWARD = re.compile(r'class (' + _ID + r');\Z')
_ROW = re.compile(r'class (' + _ID + r'): (' + _ID + r') \{ (?:itemSize|itemsCargoSize)\[\] = \{\d+, \d+\};'
                  r'( attachments\[\] = \{[^{}]*\};)? \};\Z')


def strip_inventory_block(config):
    """Return (config without the generated inventory block, report); refuse foreign content."""
    begins, ends = config.count(INVENTORY_BEGIN), config.count(INVENTORY_END)
    if begins != ends or begins > 1:
        raise ValueError('stale/malformed inventory markers')
    if not begins:
        return config, {'status': 'no_generated_block', 'removed_classes': [], 'retained_authored': []}
    match = re.search(r'(?m)^[ \t]*' + re.escape(INVENTORY_BEGIN) + r'[^\n]*\n(.*?)^[ \t]*'
                      + re.escape(INVENTORY_END) + r'[ \t]*\n?', config, flags=re.S)
    if not match:
        raise ValueError('stale/malformed inventory block')
    removed, retained = [], []
    for raw in match.group(1).splitlines():
        line = raw.strip()
        if not line or line.startswith('//') or _FORWARD.match(line):
            continue
        row = _ROW.match(line)
        if not row:
            raise ValueError('foreign config inside generated inventory block; review before removal')
        name, parent, extra = row.groups()
        if extra and AUTHORED_SLOT_ROWS.get(name) != extra:
            raise ValueError('foreign config inside generated inventory block; review before removal')
        removed.append(name)
        if extra:
            retained.append((name, parent, extra))
    outside = config[:match.start()] + config[match.end():]
    lines = ['    ' + INVENTORY_REMOVED + '; authored slot extensions kept']
    for name, parent, extra in retained:
        if not re.search(r'(?m)^[ \t]*class ' + re.escape(parent) + r'[ \t]*;', outside):
            lines.append(f'    class {parent};')
        lines.append(f'    class {name}: {parent} {{{extra} }};')
    text = config[:match.start()] + '\n'.join(lines) + '\n' + config[match.end():]
    return text, {'status': 'rebuilt', 'removed_classes': sorted(removed, key=str.lower),
                  'retained_authored': sorted(name for name, _, _ in retained)}


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def plan_inventory(addon_source=None, addon_pbo=None, pbo_out=None):
    """Build the replacement entirely in memory; nothing is written or installed."""
    if (addon_source is None) == (addon_pbo is None):
        raise ValueError(INVENTORY_GAP if addon_source is None else
                         'name exactly one of --addon-source or --addon-pbo')
    if pbo_out is None:
        raise ValueError('inventory removal needs --pbo-out (a directory for the replacement pbo)')
    from tools.package import pbo  # bundled with the operator helpers; imported only on this path
    if addon_source is not None:
        prefix = pbo.addon_prefix(addon_source)
        files = pbo.collect_addon(addon_source, prefix)
    else:
        source = Path(addon_pbo)
        if source.is_symlink() or not source.is_file():
            raise ValueError('--addon-pbo must name a regular file')
        prefix, files = pbo.parse(source.read_bytes())
    if 'config.cpp' not in files:
        raise ValueError('addon has no config.cpp')
    old = files['config.cpp'].decode('utf-8')
    new, report = strip_inventory_block(old)
    plan = {'report': report, 'blob': None}
    if report['status'] != 'rebuilt':
        return plan
    rebuilt = dict(files)
    rebuilt['config.cpp'] = new.encode('utf-8')
    blob = pbo.pack(rebuilt, prefix)
    # Prove the artefact: only config.cpp differs from the source entries.
    parsed = pbo.parse(blob, prefixes=(prefix,))[1]
    if set(parsed) != set(files) or any(parsed[n] != files[n] for n in files if n != 'config.cpp'):
        raise ValueError('replacement pbo differs outside config.cpp')
    plan['blob'] = blob
    plan['diff'] = ''.join(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                               'a/config.cpp', 'b/config.cpp'))
    plan['receipt'] = {
        'schema': 1, 'kind': 'hollow-country-inventory-removal',
        'source': 'addon_source' if addon_source is not None else 'addon_pbo',
        'source_config_sha256': _digest(files['config.cpp']),
        'new_config_sha256': _digest(rebuilt['config.cpp']),
        'pbo_sha256': _digest(blob), 'pbo_bytes': len(blob), 'prefix': prefix,
        'removed_classes': report['removed_classes'],
        'retained_authored': report['retained_authored'],
        'requiredAddons': 'unchanged', 'signed': False, 'runtime': 'PENDING',
        'next_steps': ['review config.cpp.diff', 'sign the replacement with your own key',
                       'stop the server, install it as the server addon and redistribute it to clients',
                       'keep the previous PBO for rollback']}
    out = Path(pbo_out)
    if out.is_symlink() or (out.exists() and not out.is_dir()):
        raise ValueError('--pbo-out must be a real directory')
    for name in (REPLACEMENT, RECEIPT, DIFF):
        if os.path.lexists(out / name):
            raise ValueError('refusing to overwrite: ' + name + ' exists in --pbo-out')
    return plan


def _publish(plan, pbo_out):
    out = Path(pbo_out)
    out.mkdir(parents=True, exist_ok=True)
    made = []
    try:
        for name, data in ((REPLACEMENT, plan['blob']), (DIFF, plan['diff'].encode()),
                           (RECEIPT, (json.dumps(plan['receipt'], indent=2, sort_keys=True) + '\n').encode())):
            with (out / name).open('xb') as handle:
                made.append(out / name)
                handle.write(data)
    except OSError:
        for path in made:
            path.unlink(missing_ok=True)
        raise


def _undo(mission, selected):
    removed = []
    # Loot can hold travel's types.xml, so reverse their install order.
    for name, installer in (('loot', loot_boost), ('vehicles', travel)):
        managed = economy.child(mission, installer.MANAGED)
        if name in selected and os.path.lexists(managed):
            installer.rollback(mission)
            removed.append(name)
    return removed


def remove(mission, overlays=OVERLAYS, *, stopped=False, dry_run=False,
           addon_source=None, addon_pbo=None, pbo_out=None):
    selected = tuple(overlays)
    if not selected or len(set(selected)) != len(selected) or set(selected) - set(OVERLAYS):
        raise ValueError('select unique known overlay names: loot inventory vehicles')
    if not dry_run and not stopped:
        raise ValueError('live removal requires --server-stopped; stop the server first')
    plan = None
    if 'inventory' in selected:
        # Inventory is a source/package change, never a mission receipt undo; build it first.
        plan = plan_inventory(addon_source, addon_pbo, pbo_out)
    target = economy._target(mission)
    # Validate before copytree: no symlinks, hard links, special files or escaped
    # paths can be laundered into ordinary scratch files. Never copy live saves.
    for directory, folders, files in os.walk(target, followlinks=False):
        root = Path(directory)
        for name in folders + files:
            path = root / name
            economy.child(target, path.relative_to(target).as_posix())
            if not path.is_dir():
                economy.plain_file(target, path)
        if root == target:
            folders[:] = [name for name in folders if not name.startswith('storage_')]
    with tempfile.TemporaryDirectory(prefix='hc-overlay-remove-') as temporary:
        scratch = Path(temporary) / 'mission'
        shutil.copytree(target, scratch,
                        ignore=lambda directory, names: [name for name in names
                            if Path(directory) == target and name.startswith('storage_')])
        planned = _undo(scratch, selected)
        removed = []
        if not dry_run:
            removed = _undo(target, selected)
            if plan is not None and plan['blob'] is not None:
                _publish(plan, pbo_out)
    inventory = 'not_removed; source_rebuild_required'
    if plan is not None:
        inventory = dict(plan['report'], published=bool(plan['blob'] and not dry_run))
        if plan['blob'] is not None:
            inventory.update(signed=False, pbo=REPLACEMENT, receipt=RECEIPT, diff=DIFF)
    return {'planned': planned, 'removed': removed, 'dry_run': dry_run,
            'inventory': inventory, 'runtime': 'PENDING'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mission', type=Path, required=True)
    parser.add_argument('--overlays', nargs='+', choices=OVERLAYS, default=OVERLAYS)
    parser.add_argument('--server-stopped', action='store_true')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--addon-source', type=Path,
                        help='addon source directory (config.cpp etc.) holding the generated inventory block')
    parser.add_argument('--addon-pbo', type=Path, help='installed hollowcountry.pbo to rebuild instead')
    parser.add_argument('--pbo-out', type=Path, help='new or empty directory for the replacement pbo, receipt and diff')
    args = parser.parse_args(argv)
    try:
        result = remove(args.mission, args.overlays, stopped=args.server_stopped, dry_run=args.dry_run,
                        addon_source=args.addon_source, addon_pbo=args.addon_pbo, pbo_out=args.pbo_out)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print('overlay_remove refused: ' + str(error), file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    if isinstance(result['inventory'], dict):
        print('overlay_remove runtime=PENDING; replacement pbo is unsigned: review the diff, sign it, install it '
              'on the stopped server and redistribute it to clients')
    else:
        print('overlay_remove runtime=PENDING; inventory source rebuild remains separate')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
