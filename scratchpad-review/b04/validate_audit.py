"""Read-only final checks of report coverage, citations and pinned input bytes."""
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
report = (HERE/'AUDIT.md').read_text()
log = (HERE/'COMMANDS.log').read_text()
manifest = json.loads((HERE/'INPUTS.json').read_text())
for row in manifest:
    assert hashlib.sha256(Path(row['path']).read_bytes()).hexdigest() == row['sha256'], row['path']

columns = None
counts = Counter()
for number, line in enumerate(report.splitlines(), 1):
    if not line.startswith('|'):
        columns = None
        continue
    count = len(re.findall(r'(?<!\\)\|', line))
    if columns is None:
        columns = count
    assert columns == count, ('table shape', number, count, columns)
    states = re.findall(r'\*\*(SOURCE_DONE|SOURCE_MISSING|RUNTIME_ONLY|BLOCKED_ON_ENGINE)\*\*', line)
    if states:
        assert len(states) == 1, number
        counts.update(states)
        if states[0] == 'SOURCE_DONE':
            assert 'Actual executed result(s)' in line, number
            results = re.findall(r'`(test_.*? \.\.\. ok)`', line)
            assert results, number
            for result in results:
                assert result in log, (number, result)
        if states[0] == 'SOURCE_MISSING':
            assert 'Native surface:' in line and 'Smallest owned file set:' in line, number

for prefix, maximum in [('AI', 12), ('AUD', 7), ('HOR', 11)]:
    ids = set(re.findall(r'^\| '+prefix+r'-(\d{3})\b', report, re.M))
    assert ids == {f'{n:03}' for n in range(1, maximum+1)}, (prefix, ids)
for issue in [18, 19, 20, 21, 22, 32, 44]:
    assert re.search(r'^\| #'+str(issue)+r'\b', report, re.M), issue

source_files = {p.name:p for p in (ROOT/'mods/HollowCountry/scripts').rglob('*.c')}
for filename, number in set(re.findall(r'\b((?:HC|HCHorde)[A-Za-z]+\.c):(\d+)', report)):
    path = source_files[filename]
    assert int(number) <= len(path.read_text().splitlines()), (path, number)
cache = Path('/home/david/.cache/hollow-country/native-scripts/scripts-1.30.164289')
for filename, number in set(re.findall(r'`N/([^`:\n]+):(\d+)', report)):
    path = cache / filename
    assert 0 < int(number) <= len(path.read_text().splitlines()), (path, number)

ownership = {}
for number in range(1, 10):
    lines = [line for line in report.splitlines() if line.startswith(f'| **{number} WP{number}')]
    assert len(lines) == 1, ('package', number)
    for filename in re.findall(r'`((?:I|U|E)/[^`]+)`', lines[0]):
        assert filename not in ownership, ('overlapping ownership', filename, ownership[filename], number)
        ownership[filename] = number

assert not list(HERE.rglob('__pycache__')), 'Unexpected generated bytecode'
print(f'PASS: {len(manifest)} pinned original inputs unchanged.')
print('PASS: all 30 AI/audio/horde IDs, all seven issues, and one classification per table row.')
print(f'PASS: {sum(counts.values())} criteria: '+', '.join(f'{key}={counts[key]}' for key in sorted(counts)))
print('PASS: table shapes, source/native citation bounds and pasted executed GREEN result lines.')
print(f'PASS: nine ranked work packages, {len(ownership)} exclusive I/U/E file leases; no generated bytecode.')
